#!/usr/bin/env node
/**
 * 부산 시군구 GeoJSON(EPSG:5179) → WGS84 경계 TS 생성
 * 소스: statgarten/maps (통계청 SGIS 기반)
 *   https://github.com/statgarten/maps/blob/main/json/부산광역시_시군구_경계.json
 */
const fs = require('fs');
const path = require('path');
const proj4 = require('proj4');

const projectRoot = path.join(__dirname, '..');
const sourcePath = path.join(projectRoot, 'assets', 'map', 'busan-sigungu.geojson');
const fallbackSourcePath = path.join(projectRoot, 'scripts', '_busan_sigungu.geojson');
const outPath = path.join(projectRoot, 'src', 'constants', 'eventZone', 'busanDistrictBoundaries.ts');

const DOWNLOAD_URL =
  'https://raw.githubusercontent.com/statgarten/maps/main/json/%EB%B6%80%EC%82%B0%EA%B4%91%EC%97%AD%EC%8B%9C_%EC%8B%9C%EA%B5%B0%EA%B5%AC_%EA%B2%BD%EA%B3%84.json';

proj4.defs(
  'EPSG:5179',
  '+proj=tmerc +lat_0=38 +lon_0=127.5 +k=0.9996 +x_0=1000000 +y_0=2000000 +ellps=bessel +towgs84=-115.80,474.99,674.11,1.16,-2.31,-1.63,6.43 +units=m +no_defs',
);

const LABEL_TO_DISTRICT_ID = {
  중구: 'CD26110',
  서구: 'CD26140',
  동구: 'CD26170',
  영도구: 'CD26200',
  부산진구: 'CD26230',
  동래구: 'CD26260',
  남구: 'CD26290',
  북구: 'CD26320',
  해운대구: 'CD26350',
  사하구: 'CD26380',
  금정구: 'CD26410',
  강서구: 'CD26440',
  연제구: 'CD26470',
  사상구: 'CD26530',
  수영구: 'CD26500',
  기장군: 'CD26710',
};

function toWgs84(x, y) {
  const [lng, lat] = proj4('EPSG:5179', 'EPSG:4326', [x, y]);
  return { lat: roundCoord(lat), lng: roundCoord(lng) };
}

function roundCoord(value) {
  return Math.round(value * 1e6) / 1e6;
}

function perpendicularDistance(point, lineStart, lineEnd) {
  const dx = lineEnd.lng - lineStart.lng;
  const dy = lineEnd.lat - lineStart.lat;
  if (dx === 0 && dy === 0) {
    return Math.hypot(point.lng - lineStart.lng, point.lat - lineStart.lat);
  }
  const t =
    ((point.lng - lineStart.lng) * dx + (point.lat - lineStart.lat) * dy) / (dx * dx + dy * dy);
  const projLng = lineStart.lng + t * dx;
  const projLat = lineStart.lat + t * dy;
  return Math.hypot(point.lng - projLng, point.lat - projLat);
}

function simplifyRing(points, tolerance) {
  if (points.length <= 4) {
    return points;
  }

  let maxDistance = 0;
  let index = 0;
  const end = points.length - 1;

  for (let i = 1; i < end; i += 1) {
    const distance = perpendicularDistance(points[i], points[0], points[end]);
    if (distance > maxDistance) {
      maxDistance = distance;
      index = i;
    }
  }

  if (maxDistance > tolerance) {
    const left = simplifyRing(points.slice(0, index + 1), tolerance);
    const right = simplifyRing(points.slice(index), tolerance);
    return [...left.slice(0, -1), ...right];
  }

  return [points[0], points[end]];
}

function convertRing(ring) {
  const converted = ring.map(([x, y]) => toWgs84(x, y));
  return simplifyRing(converted, 0.0008);
}

function geometryToRings(geometry) {
  if (!geometry) {
    return [];
  }

  if (geometry.type === 'Polygon') {
    return geometry.coordinates.map(convertRing).filter(ring => ring.length >= 3);
  }

  if (geometry.type === 'MultiPolygon') {
    return geometry.coordinates
      .flatMap(polygon => polygon.map(convertRing))
      .filter(ring => ring.length >= 3);
  }

  return [];
}

async function ensureSourceGeoJson() {
  if (fs.existsSync(sourcePath)) {
    return sourcePath;
  }
  if (fs.existsSync(fallbackSourcePath)) {
    fs.mkdirSync(path.dirname(sourcePath), { recursive: true });
    fs.copyFileSync(fallbackSourcePath, sourcePath);
    return sourcePath;
  }

  console.log('[Bu-Ting] Downloading Busan sigungu GeoJSON…');
  const res = await fetch(DOWNLOAD_URL);
  if (!res.ok) {
    throw new Error(`Download failed (${res.status})`);
  }
  fs.mkdirSync(path.dirname(sourcePath), { recursive: true });
  fs.writeFileSync(sourcePath, Buffer.from(await res.arrayBuffer()));
  return sourcePath;
}

async function main() {
  const geoPath = await ensureSourceGeoJson();
  const collection = JSON.parse(fs.readFileSync(geoPath, 'utf8'));
  const boundaries = [];

  for (const feature of collection.features ?? []) {
    const labelKo = feature.properties?.title;
    const districtId = LABEL_TO_DISTRICT_ID[labelKo];
    if (!districtId) {
      console.warn('[Bu-Ting] Unknown district title:', labelKo);
      continue;
    }

    const rings = geometryToRings(feature.geometry);
    if (rings.length === 0) {
      continue;
    }

    boundaries.push({ districtId, labelKo, rings });
  }

  boundaries.sort((a, b) => a.districtId.localeCompare(b.districtId));

  const content = `/** Generated by scripts/build-busan-district-boundaries.cjs — do not edit manually. */
import type { EventZoneCoordinate } from '../../types/eventZone';

export type BusanDistrictBoundary = {
  districtId: string;
  labelKo: string;
  rings: EventZoneCoordinate[][];
};

export const BUSAN_DISTRICT_BOUNDARIES: BusanDistrictBoundary[] = ${JSON.stringify(boundaries, null, 2)};
`;

  fs.writeFileSync(outPath, content, 'utf8');
  const pointCount = boundaries.reduce(
    (sum, district) => sum + district.rings.reduce((ringSum, ring) => ringSum + ring.length, 0),
    0,
  );
  console.log(
    `[Bu-Ting] Wrote ${path.relative(projectRoot, outPath)} (${boundaries.length} districts, ${pointCount} points)`,
  );
}

main().catch(error => {
  console.error('[Bu-Ting] build-busan-district-boundaries failed', error);
  process.exit(1);
});
