#!/usr/bin/env node
/**
 * .env OAuth 키 → src/constants/oauthConfig.ts 및 네이티브 설정 동기화
 */
const fs = require('fs');
const path = require('path');

const { loadProjectEnv } = require('./lib/load-env.cjs');

const projectRoot = path.join(__dirname, '..');

function envOrEmpty(key) {
  return process.env[key]?.trim() ?? '';
}

function writeOAuthConfig(keys) {
  const configPath = path.join(projectRoot, 'src', 'constants', 'oauthConfig.ts');
  const esc = value => value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  const content = `/** Generated by scripts/sync-oauth-config.cjs — do not edit manually. */
export const OAUTH_CONFIG = {
  googleWebClientId: "${esc(keys.googleWebClientId)}",
  googleIosClientId: "${esc(keys.googleIosClientId)}",
  kakaoNativeAppKey: "${esc(keys.kakaoNativeAppKey)}",
  naverClientId: "${esc(keys.naverClientId)}",
  naverClientSecret: "${esc(keys.naverClientSecret)}",
  naverAppName: "${esc(keys.naverAppName)}",
  naverUrlScheme: "${esc(keys.naverUrlScheme)}",
} as const;
`;
  fs.writeFileSync(configPath, content, 'utf8');
  return configPath;
}

function upsertStringXml(name, value) {
  const stringsPath = path.join(
    projectRoot,
    'android',
    'app',
    'src',
    'main',
    'res',
    'values',
    'oauth_strings.xml',
  );
  const escaped = value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '\\"');
  const content = `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <string name="kakao_app_key" translatable="false">${escaped}</string>
</resources>
`;
  fs.writeFileSync(stringsPath, content, 'utf8');
}

function patchAndroidManifest(kakaoNativeAppKey) {
  const manifestPath = path.join(
    projectRoot,
    'android',
    'app',
    'src',
    'main',
    'AndroidManifest.xml',
  );
  let manifest = fs.readFileSync(manifestPath, 'utf8');
  const kakaoScheme = kakaoNativeAppKey ? `kakao${kakaoNativeAppKey}` : 'kakaoYOUR_NATIVE_APP_KEY';

  const kakaoActivity = `
      <activity
        android:name="com.kakao.sdk.auth.AuthCodeHandlerActivity"
        android:exported="true">
        <intent-filter>
            <action android:name="android.intent.action.VIEW" />
            <category android:name="android.intent.category.DEFAULT" />
            <category android:name="android.intent.category.BROWSABLE" />
            <data
              android:host="oauth"
              android:scheme="${kakaoScheme}" />
        </intent-filter>
      </activity>`;

  const kakaoActivityRegex =
    /<activity\s+[^>]*android:name="com\.kakao\.sdk\.auth\.AuthCodeHandlerActivity"[^>]*>[\s\S]*?<\/activity>/;

  if (manifest.includes('com.kakao.sdk.auth.AuthCodeHandlerActivity')) {
    manifest = manifest.replace(kakaoActivityRegex, kakaoActivity.trim());
  } else {
    manifest = manifest.replace(
      '</application>',
      `${kakaoActivity}\n    </application>`,
    );
  }

  fs.writeFileSync(manifestPath, manifest, 'utf8');
}

function patchIosInfoPlist(keys, naverOauthEnabled) {
  const plistPath = path.join(projectRoot, 'ios', 'BUTingMobile', 'Info.plist');
  let plist = fs.readFileSync(plistPath, 'utf8');
  const kakaoKey = keys.kakaoNativeAppKey;
  const naverScheme = keys.naverUrlScheme || 'butingnaverlogin';

  const kakaoUrlBlock = kakaoKey
    ? `
	<dict>
		<key>CFBundleTypeRole</key>
		<string>Editor</string>
		<key>CFBundleURLSchemes</key>
		<array>
			<string>kakao${kakaoKey}</string>
		</array>
	</dict>`
    : '';

  const naverUrlBlock = naverOauthEnabled
    ? `
	<dict>
		<key>CFBundleTypeRole</key>
		<string>Editor</string>
		<key>CFBundleURLName</key>
		<string>naver</string>
		<key>CFBundleURLSchemes</key>
		<array>
			<string>${naverScheme}</string>
		</array>
	</dict>`
    : '';

  const urlTypesBlock = `<key>CFBundleURLTypes</key>
<array>${kakaoUrlBlock}${naverUrlBlock}
</array>`;

  if (plist.includes('<key>CFBundleURLTypes</key>')) {
    plist = plist.replace(
      /<key>CFBundleURLTypes<\/key>[\s\S]*?<\/array>/,
      urlTypesBlock,
    );
  } else {
    plist = plist.replace(
      '<key>CFBundleVersion</key>',
      `${urlTypesBlock}
	<key>CFBundleVersion</key>`,
    );
  }

  const queries = [
    'kakaokompassauth',
    'kakaolink',
    ...(naverOauthEnabled ? ['naversearchapp', 'naversearchthirdlogin'] : []),
  ];
  const queriesBlock = `<key>LSApplicationQueriesSchemes</key>
<array>
${queries.map(q => `\t\t<string>${q}</string>`).join('\n')}
</array>`;

  if (plist.includes('<key>LSApplicationQueriesSchemes</key>')) {
    plist = plist.replace(
      /<key>LSApplicationQueriesSchemes<\/key>[\s\S]*?<\/array>/,
      queriesBlock,
    );
  } else {
    plist = plist.replace(
      '<key>NSAppTransportSecurity</key>',
      `${queriesBlock}
	<key>NSAppTransportSecurity</key>`,
    );
  }

  if (kakaoKey) {
    if (plist.includes('<key>KAKAO_APP_KEY</key>')) {
      plist = plist.replace(
        /<key>KAKAO_APP_KEY<\/key>\s*<string>[^<]*<\/string>/,
        `<key>KAKAO_APP_KEY</key>\n\t<string>${kakaoKey}</string>`,
      );
    } else {
      plist = plist.replace(
        '<key>LSRequiresIPhoneOS</key>',
        `<key>KAKAO_APP_KEY</key>\n\t<string>${kakaoKey}</string>\n\t<key>LSRequiresIPhoneOS</key>`,
      );
    }
  }

  fs.writeFileSync(plistPath, plist, 'utf8');
}

function main() {
  loadProjectEnv({ root: projectRoot });

  const naverOauthEnabled = process.env.NAVER_OAUTH_ENABLED === 'true';

  const keys = {
    googleWebClientId: envOrEmpty('GOOGLE_OAUTH_WEB_CLIENT_ID'),
    googleIosClientId: envOrEmpty('GOOGLE_OAUTH_IOS_CLIENT_ID'),
    kakaoNativeAppKey:
      envOrEmpty('KAKAO_NATIVE_APP_KEY') || envOrEmpty('KAKAO_JAVASCRIPT_KEY'),
    naverClientId: envOrEmpty('NAVER_CLIENT_ID'),
    naverClientSecret: envOrEmpty('NAVER_CLIENT_SECRET'),
    naverAppName: envOrEmpty('NAVER_APP_NAME') || '부팅',
    naverUrlScheme: envOrEmpty('NAVER_URL_SCHEME') || 'butingnaverlogin',
  };

  const configPath = writeOAuthConfig(keys);
  console.log(`[Bu-Ting] OAuth config synced → ${path.relative(projectRoot, configPath)}`);

  if (keys.kakaoNativeAppKey) {
    upsertStringXml('kakao_app_key', keys.kakaoNativeAppKey);
    patchAndroidManifest(keys.kakaoNativeAppKey);
    patchIosInfoPlist(keys, naverOauthEnabled);
    console.log('[Bu-Ting] Kakao native keys synced to Android/iOS');
  } else {
    console.warn('[Bu-Ting] KAKAO_NATIVE_APP_KEY not set — Kakao login native config skipped.');
  }

  if (!naverOauthEnabled) {
    console.log('[Bu-Ting] Naver OAuth disabled — skipping Naver native config.');
  } else if (!keys.naverClientId || !keys.naverClientSecret) {
    console.warn('[Bu-Ting] NAVER_CLIENT_ID/SECRET not set — Naver login disabled.');
  }
  if (!keys.googleWebClientId) {
    console.warn('[Bu-Ting] GOOGLE_OAUTH_WEB_CLIENT_ID not set — Google Sign-In disabled.');
  }
}

main();
