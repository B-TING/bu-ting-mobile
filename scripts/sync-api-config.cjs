#!/usr/bin/env node
/**
 * .env 의 API_BASE_URL 을 src/constants/api/apiBaseUrl.ts 에 동기화합니다.
 */
const fs = require('fs');
const path = require('path');

const { loadProjectEnv } = require('./lib/load-env.cjs');

const projectRoot = path.join(__dirname, '..');
const DEFAULT_API_BASE_URL = 'http://localhost:8080';

function resolveApiBaseUrl() {
  loadProjectEnv({ root: projectRoot });
  const baseUrl = process.env.API_BASE_URL?.trim();
  return baseUrl || DEFAULT_API_BASE_URL;
}

function writeApiBaseUrlConfig(baseUrl) {
  const configPath = path.join(projectRoot, 'src', 'constants', 'api', 'apiBaseUrl.ts');
  const escaped = baseUrl.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  const content = `/** Generated by scripts/sync-api-config.cjs — do not edit manually. */
export const API_BASE_URL = "${escaped}";
`;
  fs.writeFileSync(configPath, content, 'utf8');
  return configPath;
}

function writeApiConfig(googleWebClientId, kakaoRestApiKey) {
  const configPath = path.join(projectRoot, 'src', 'constants', 'api', 'apiConfig.ts');
  const esc = value => value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  const content = `/** Generated by scripts/sync-api-config.cjs — do not edit manually. */
import type { OAuthProvider } from '../../types/auth';

export { API_BASE_URL } from './apiBaseUrl';

export const AUTH_ENDPOINTS = {
  oauthLogin: '/api/v1/auth/oauth/login',
} as const;

export const TRAVEL_SURVEY_ENDPOINTS = {
  profile: '/api/v1/travel-surveys',
} as const;

export const USER_ENDPOINTS = {
  me: '/api/v1/users/me',
} as const;

export const PLACES_ENDPOINTS = {
  search: '/api/v1/places',
  location: '/api/v1/places/location',
  festivals: '/api/v1/places/festivals',
  detail: (contentId: string) => \`/api/v1/places/\${contentId}/detail\`,
} as const;

export const CHAT_ENDPOINTS = {
  roomsByZone: '/api/v1/chat/rooms/zone',
  messages: (roomId: string) => \`/api/v1/chat/rooms/\${roomId}/messages\`,
  webSocketPath: '/ws-stomp',
} as const;

export const TRAVEL_ENDPOINTS = {
  travels: '/api/v1/travels',
  travelPlans: (travelId: string) => \`/api/v1/travels/\${travelId}/plans\`,
  planPlaces: (planId: string) => \`/api/v1/plans/\${planId}/places\`,
  planPlaceSequence: (planId: string) => \`/api/v1/plans/\${planId}/places/sequence\`,
  planPlaceById: (planPlaceId: string) => \`/api/v1/plans/places/\${planPlaceId}\`,
} as const;

export type OAuthClientConfig = {
  clientId: string;
  redirectUri: string;
  scope: string;
};

/** Provider authorize URL (redirectUri는 buildOAuthRedirectUri로 런타임 생성) */
export const OAUTH_CLIENT_CONFIG: Record<OAuthProvider, OAuthClientConfig> = {
  google: {
    clientId: "${esc(googleWebClientId)}",
    redirectUri: '',
    scope: 'openid email profile',
  },
  kakao: {
    clientId: "${esc(kakaoRestApiKey)}",
    redirectUri: '',
    scope: 'account_email profile_nickname',
  },
  naver: {
    clientId: '',
    redirectUri: '',
    scope: 'email name nickname',
  },
};

export const OAUTH_AUTHORIZE_URL: Record<OAuthProvider, string> = {
  google: 'https://accounts.google.com/o/oauth2/v2/auth',
  kakao: 'https://kauth.kakao.com/oauth/authorize',
  naver: 'https://nid.naver.com/oauth2.0/authorize',
};
`;
  fs.writeFileSync(configPath, content, 'utf8');
  return configPath;
}

function main() {
  loadProjectEnv({ root: projectRoot });
  const baseUrl = resolveApiBaseUrl();
  const googleWebClientId = process.env.GOOGLE_OAUTH_WEB_CLIENT_ID?.trim() ?? '';
  const kakaoRestApiKey =
    process.env.KAKAO_REST_API_KEY?.trim() ||
    process.env.KAKAO_NATIVE_APP_KEY?.trim() ||
    process.env.KAKAO_JAVASCRIPT_KEY?.trim() ||
    '';

  if (!process.env.API_BASE_URL?.trim()) {
    console.warn(
      `[Bu-Ting] API_BASE_URL not set — using default: ${DEFAULT_API_BASE_URL}`,
    );
    console.warn('  Copy .env.example → .env and run: npm run api:sync');
  }

  const baseUrlPath = writeApiBaseUrlConfig(baseUrl);
  const apiConfigPath = writeApiConfig(googleWebClientId, kakaoRestApiKey);
  console.log(
    `[Bu-Ting] API config synced → ${path.relative(projectRoot, baseUrlPath)}, ${path.relative(projectRoot, apiConfigPath)}`,
  );
}

main();
