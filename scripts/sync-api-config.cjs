#!/usr/bin/env node
/**
 * .env 의 API_BASE_URL 을 src/constants/apiBaseUrl.ts 에 동기화합니다.
 */
const fs = require('fs');
const path = require('path');

const { loadProjectEnv } = require('./lib/load-env.cjs');

const projectRoot = path.join(__dirname, '..');
const DEFAULT_API_BASE_URL = 'http://localhost:8080';

function resolveApiBaseUrl() {
  loadProjectEnv({ root: projectRoot });
  const baseUrl = process.env.API_BASE_URL?.trim();
  return baseUrl || DEFAULT_API_BASE_URL;
}

function writeApiBaseUrlConfig(baseUrl) {
  const configPath = path.join(projectRoot, 'src', 'constants', 'apiBaseUrl.ts');
  const escaped = baseUrl.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  const content = `/** Generated by scripts/sync-api-config.cjs — do not edit manually. */
export const API_BASE_URL = "${escaped}";
`;
  fs.writeFileSync(configPath, content, 'utf8');
  return configPath;
}

function writeApiConfig() {
  const configPath = path.join(projectRoot, 'src', 'constants', 'apiConfig.ts');
  const content = `/** Generated by scripts/sync-api-config.cjs — do not edit manually. */
import type { OAuthProvider } from '../types/auth';

export { API_BASE_URL } from './apiBaseUrl';

export const AUTH_ENDPOINTS = {
  oauthLogin: '/api/v1/auth/oauth/login',
} as const;

export type OAuthClientConfig = {
  clientId: string;
  redirectUri: string;
  scope: string;
};

/** Provider authorize URL에 쓸 클라이언트 설정 (비밀키 제외) */
export const OAUTH_CLIENT_CONFIG: Record<OAuthProvider, OAuthClientConfig> = {
  google: {
    clientId: '',
    redirectUri: '',
    scope: 'openid email profile',
  },
  kakao: {
    clientId: '',
    redirectUri: '',
    scope: 'account_email profile_nickname',
  },
  naver: {
    clientId: '',
    redirectUri: '',
    scope: 'email name nickname',
  },
};

export const OAUTH_AUTHORIZE_URL: Record<OAuthProvider, string> = {
  google: 'https://accounts.google.com/o/oauth2/v2/auth',
  kakao: 'https://kauth.kakao.com/oauth/authorize',
  naver: 'https://nid.naver.com/oauth2.0/authorize',
};
`;
  fs.writeFileSync(configPath, content, 'utf8');
  return configPath;
}

function main() {
  const baseUrl = resolveApiBaseUrl();

  if (!process.env.API_BASE_URL?.trim()) {
    console.warn(
      `[Bu-Ting] API_BASE_URL not set — using default: ${DEFAULT_API_BASE_URL}`,
    );
    console.warn('  Copy .env.example → .env and run: npm run api:sync');
  }

  const baseUrlPath = writeApiBaseUrlConfig(baseUrl);
  const apiConfigPath = writeApiConfig();
  console.log(
    `[Bu-Ting] API config synced → ${path.relative(projectRoot, baseUrlPath)}, ${path.relative(projectRoot, apiConfigPath)}`,
  );
}

main();
