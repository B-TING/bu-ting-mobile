#!/usr/bin/env node
/**
 * .env 의 카카오맵 JavaScript 키를 src/constants/kakaoMapConfig.ts 에 동기화합니다.
 */
const fs = require('fs');
const path = require('path');

const { loadProjectEnv } = require('./lib/load-env.cjs');

const projectRoot = path.join(__dirname, '..');

function resolveKakaoMapJsKey() {
  loadProjectEnv({ root: projectRoot });
  const jsKey = process.env.KAKAO_JAVASCRIPT_KEY?.trim();
  if (jsKey) {
    return jsKey;
  }
  return process.env.KAKAO_NATIVE_APP_KEY?.trim() ?? '';
}

function writeKakaoConfig(jsKey) {
  const configPath = path.join(projectRoot, 'src', 'constants', 'kakaoMapConfig.ts');
  const escaped = jsKey.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  const content = `/** Generated by scripts/sync-kakao-map-key.cjs — do not edit manually. */
export const KAKAO_MAP_JS_KEY = "${escaped}";
`;
  fs.writeFileSync(configPath, content, 'utf8');
  return configPath;
}

function main() {
  const jsKey = resolveKakaoMapJsKey();

  if (!jsKey) {
    console.warn('[Bu-Ting] KAKAO_JAVASCRIPT_KEY not set — writing empty kakao map config stub.');
    console.warn('  Copy .env.example → .env and run: npm run kakao:sync');
  } else if (!process.env.KAKAO_JAVASCRIPT_KEY?.trim() && process.env.KAKAO_NATIVE_APP_KEY?.trim()) {
    console.warn(
      '[Bu-Ting] KAKAO_JAVASCRIPT_KEY missing — using KAKAO_NATIVE_APP_KEY as temporary fallback.',
    );
    console.warn('  WebView 지도는 JavaScript 키 사용을 권장합니다.');
  }

  const configPath = writeKakaoConfig(jsKey);
  console.log(`[Bu-Ting] Kakao Map config synced → ${path.relative(projectRoot, configPath)}`);
}

main();
