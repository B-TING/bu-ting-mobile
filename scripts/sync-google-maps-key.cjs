#!/usr/bin/env node
/**
 * .env 의 Google Maps API 키를 네이티브 빌드 설정에 동기화합니다.
 *
 * GOOGLE_MAPS_API_KEY 가 없으면 GOOGLE_PLACES_API_KEY 를 사용합니다.
 */
const fs = require('fs');
const path = require('path');

const { loadProjectEnv } = require('./lib/load-env.cjs');

const projectRoot = path.join(__dirname, '..');

function resolveMapsApiKey() {
  loadProjectEnv({ root: projectRoot });
  const mapsKey = process.env.GOOGLE_MAPS_API_KEY?.trim();
  if (mapsKey) {
    return mapsKey;
  }
  const placesKey = process.env.GOOGLE_PLACES_API_KEY?.trim();
  if (placesKey) {
    return placesKey;
  }
  return null;
}

function writeAndroidKey(apiKey) {
  const valuesDir = path.join(
    projectRoot,
    'android',
    'app',
    'src',
    'main',
    'res',
    'values',
  );
  fs.mkdirSync(valuesDir, { recursive: true });

  const xmlPath = path.join(valuesDir, 'google_maps_api.xml');
  const xml = `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <string name="google_maps_key" translatable="false">${apiKey}</string>
</resources>
`;
  fs.writeFileSync(xmlPath, xml, 'utf8');
  return xmlPath;
}

function writeIosKey(apiKey) {
  const swiftPath = path.join(projectRoot, 'ios', 'BUTingMobile', 'GoogleMapsApiKey.swift');
  const swift = `// Generated by scripts/sync-google-maps-key.cjs — do not edit manually.
enum GoogleMapsApiKey {
  static let value = "${apiKey.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"
}
`;
  fs.writeFileSync(swiftPath, swift, 'utf8');
  return swiftPath;
}

function main() {
  const apiKey = resolveMapsApiKey();
  if (!apiKey) {
    console.warn(
      '[Bu-Ting] GOOGLE_MAPS_API_KEY (or GOOGLE_PLACES_API_KEY) not set — writing empty maps key stubs.',
    );
    console.warn('  Copy .env.example → .env and run: npm run maps:sync');
    writeAndroidKey('');
    writeIosKey('');
    process.exit(0);
  }

  const androidPath = writeAndroidKey(apiKey);
  const iosPath = writeIosKey(apiKey);
  console.log(`[Bu-Ting] Google Maps API key synced →`);
  console.log(`  ${path.relative(projectRoot, androidPath)}`);
  console.log(`  ${path.relative(projectRoot, iosPath)}`);
}

main();
